'use strict';

// The alert looks' recorded sounds (public/overlay/objects/sounds/<family>/, docs/features/look-sounds.md).
// Every look sound has a default recording, <key>.<hash>.mp3, and a second version a streamer may pick
// instead, <key>.2.<hash>.mp3; <hash> is the first ten hex digits of the file's SHA-256, so a new
// recording gets a new name and a browser (or Cloudflare) may keep a file for a year. This writes the
// table the kit registers them from, sounds/manifest.js, from the files on disk.
//   node scripts/look-sounds.js           writes manifest.js
//   node scripts/look-sounds.js --check   exits 1 when manifest.js is not what the files say
// LOOK_SOUNDS_DIR overrides the folder (the tests use a copy).

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const DIR = process.env.LOOK_SOUNDS_DIR || path.join(__dirname, '..', 'public', 'overlay', 'objects', 'sounds');
const NAME = /^([A-Za-z][A-Za-z0-9]*)(\.2)?\.([0-9a-f]{10})\.mp3$/;

// { key: [default file, second version's file] } from the folder; throws on a name or content that is off.
function scan(dir = DIR) {
  const table = {};
  const families = fs.readdirSync(dir).filter((f) => fs.statSync(path.join(dir, f)).isDirectory()).sort();
  for (const family of families) {
    for (const file of fs.readdirSync(path.join(dir, family)).sort()) {
      const m = NAME.exec(file);
      if (!m) throw new Error(`${family}/${file}: a recording is named <key>.<hash>.mp3 or <key>.2.<hash>.mp3`);
      const hash = crypto.createHash('sha256').update(fs.readFileSync(path.join(dir, family, file))).digest('hex').slice(0, 10);
      if (hash !== m[3]) throw new Error(`${family}/${file}: the name says ${m[3]} but the file hashes to ${hash}`);
      const entry = table[m[1]] || (table[m[1]] = [null, null]);
      const slot = m[2] ? 1 : 0;
      if (entry[slot]) throw new Error(`${m[1]}: two ${slot ? 'second versions' : 'default recordings'} (${entry[slot]}, ${family}/${file})`);
      entry[slot] = `${family}/${file}`;
    }
  }
  for (const [key, files] of Object.entries(table)) {
    if (!files[0]) throw new Error(`${key}: a second version without a default recording`);
  }
  return table;
}

function render(table) {
  const rows = Object.keys(table).sort().map((key) => `    ${JSON.stringify(key)}: ${JSON.stringify(table[key].filter(Boolean))},`);
  return `'use strict';

// Generated by scripts/look-sounds.js from the recordings next to it; run it again after adding or
// replacing one, never edit this by hand. Each look sound: [default recording, second version], under
// /overlay/objects/sounds/. Served joined after the family files (services/alertStyleBundle.js).
(function (root) {
  var K = (root && root.ATLETA_KIT) || require('../kit.js');
  K.registerSoundFiles({
${rows.join('\n')}
  });
})(typeof window !== 'undefined' ? window : null);
`;
}

if (require.main === module) {
  const file = path.join(DIR, 'manifest.js');
  const text = render(scan());
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
    if (current !== text) {
      console.error('sounds/manifest.js is out of date: run node scripts/look-sounds.js');
      process.exit(1);
    }
    console.log('sounds/manifest.js matches the recordings');
  } else {
    fs.writeFileSync(file, text);
    console.log(`wrote ${path.relative(process.cwd(), file)} (${Object.keys(scan()).length} sounds)`);
  }
}

module.exports = { scan, render, NAME };
